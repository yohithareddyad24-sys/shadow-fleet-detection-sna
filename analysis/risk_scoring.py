"""
Vessel Network Risk Scoring Engine.

Combines Social Network Analysis (SNA) centrality measures with vessel attribute risk
indicators to calculate an explainable, composite Network Risk Score (0.0 to 1.0).

DISCLAIMER: Risk scores are priority triage metrics designed for exploratory analysis
and anomaly ranking. They do NOT constitute legal proof or definitive determination
of illicit maritime activity or shadow fleet affiliation.
"""

from typing import Dict, Any, Optional
import pandas as pd
import numpy as np


DEFAULT_WEIGHTS = {
    "weight_degree": 0.20,
    "weight_betweenness": 0.30,
    "weight_flag": 0.25,
    "weight_ais_gaps": 0.15,
    "weight_spoofing": 0.10,
}


def compute_composite_risk_scores(
    metrics_df: pd.DataFrame,
    weights: Optional[Dict[str, float]] = None,
) -> pd.DataFrame:
    """
    Compute normalized composite risk scores combining SNA centralities and vessel indicators.

    Formula:
        Score = w_deg * C_deg + w_bet * C_bet + w_flag * I_flag + w_gap * N_gap_norm + w_spf * N_spf_norm

    Args:
        metrics_df: DataFrame generated by sna_metrics.compute_sna_metrics.
        weights: Optional dictionary overriding default scoring weights.

    Returns:
        pd.DataFrame sorted by 'composite_risk_score' descending, with added columns:
            - 'composite_risk_score' (0.0 - 1.0)
            - 'risk_tier' (CRITICAL_MONITORING, ELEVATED_ATTENTION, MODERATE, BASELINE)
            - 'primary_risk_driver' (string descriptor of largest risk factor)
    """
    if metrics_df.empty:
        return pd.DataFrame()

    df = metrics_df.copy()
    cfg = DEFAULT_WEIGHTS.copy()
    if weights:
        cfg.update(weights)

    # Normalize weights so they sum to 1.0
    weight_sum = sum(cfg.values())
    if weight_sum <= 0:
        raise ValueError("Sum of risk weights must be greater than zero.")
    normalized_weights = {k: v / weight_sum for k, v in cfg.items()}

    # Extract or normalize components
    c_deg = df["degree_centrality"].clip(0.0, 1.0)
    c_bet = df["betweenness_centrality"].clip(0.0, 1.0)
    i_flag = df["flag_risk_weight"].clip(0.0, 1.0)

    # Min-max normalization for count indicators with safe denominator
    max_gaps = df["ais_gap_count"].max()
    norm_gaps = (df["ais_gap_count"] / max_gaps) if max_gaps > 0 else df["ais_gap_count"] * 0.0

    max_spoofs = df["spoofing_incident_count"].max()
    norm_spoofs = (df["spoofing_incident_count"] / max_spoofs) if max_spoofs > 0 else df["spoofing_incident_count"] * 0.0

    # Calculate individual weighted contributions
    df["contrib_degree"] = round(c_deg * normalized_weights["weight_degree"], 4)
    df["contrib_betweenness"] = round(c_bet * normalized_weights["weight_betweenness"], 4)
    df["contrib_flag"] = round(i_flag * normalized_weights["weight_flag"], 4)
    df["contrib_ais_gaps"] = round(norm_gaps * normalized_weights["weight_ais_gaps"], 4)
    df["contrib_spoofing"] = round(norm_spoofs * normalized_weights["weight_spoofing"], 4)

    # Total score bounded [0.0, 1.0]
    total_score = (
        df["contrib_degree"]
        + df["contrib_betweenness"]
        + df["contrib_flag"]
        + df["contrib_ais_gaps"]
        + df["contrib_spoofing"]
    ).clip(0.0, 1.0)

    df["composite_risk_score"] = round(total_score, 4)
    df["risk_tier"] = df["composite_risk_score"].apply(categorize_risk_tiers)

    # Determine primary risk driver
    contrib_cols = {
        "High Degree Hub": "contrib_degree",
        "Intermediary Bridge (Betweenness)": "contrib_betweenness",
        "Flag of Convenience": "contrib_flag",
        "Dark AIS Gaps": "contrib_ais_gaps",
        "Spoofing Discrepancy": "contrib_spoofing",
    }

    def get_top_driver(row):
        highest_label = "Baseline"
        highest_val = -1.0
        for label, col in contrib_cols.items():
            if row[col] > highest_val:
                highest_val = row[col]
                highest_label = label
        return highest_label

    df["primary_risk_driver"] = df.apply(get_top_driver, axis=1)

    df.sort_values(by="composite_risk_score", ascending=False, inplace=True)
    df.reset_index(drop=True, inplace=True)
    return df


def categorize_risk_tiers(score: float) -> str:
    """
    Map numeric risk score to qualitative alert category.

    Tiers:
        - CRITICAL_MONITORING: >= 0.65
        - ELEVATED_ATTENTION: 0.45 to < 0.65
        - MODERATE_INTERACTION: 0.25 to < 0.45
        - BASELINE_LEGITIMATE: < 0.25
    """
    if score >= 0.65:
        return "CRITICAL_MONITORING"
    elif score >= 0.45:
        return "ELEVATED_ATTENTION"
    elif score >= 0.25:
        return "MODERATE_INTERACTION"
    else:
        return "BASELINE_LEGITIMATE"
